print(f"{not True and False}   # not True is False; False and False is False")

print(f"{True or False and False}   # True, because since we use or, it could either be True or False, in which we are given false so its true")

print(f"{not (5 > 3)}   # False, because its True that 5 >3, but since we used not, it becomes False")

print(f"{10 == 10 and 4 != 4}   # False, because 10 == 10 is True, but 4 != 4 is False, so its False")

print(f"{not False or not True}   # True, because not False is True, and not True is False, so its True")
